import { Buffer } from "node:buffer";

/** QR Code Model 2, módulo 6, ECC M — comando nativo ESC/POS (GS ( k). */
export function bytesQrEscpos(conteudo: string): Buffer {
	const content = Buffer.from(conteudo, "latin1");
	const storeLen = content.length + 3;
	const pL = storeLen & 0xff;
	const pH = (storeLen >> 8) & 0xff;
	return Buffer.concat([
		Buffer.from([0x1d, 0x28, 0x6b, 0x04, 0x00, 0x31, 0x41, 0x32, 0x00]),
		Buffer.from([0x1d, 0x28, 0x6b, 0x03, 0x00, 0x31, 0x43, 0x06]),
		Buffer.from([0x1d, 0x28, 0x6b, 0x03, 0x00, 0x31, 0x45, 0x31]),
		Buffer.from([0x1d, 0x28, 0x6b, pL, pH, 0x31, 0x50, 0x30]),
		content,
		Buffer.from([0x1d, 0x28, 0x6b, 0x03, 0x00, 0x31, 0x51, 0x30]),
	]);
}
